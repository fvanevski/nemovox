"""Recording-bound caption routing hints, never source or identity authority."""
from __future__ import annotations

from copy import deepcopy
import math

CAPTION_QUESTION = "Read the source-language dialogue captions in the referenced occurrence."
CAPTION_FOCUS = "caption"


def _number(value):
    return type(value) in (int, float) and math.isfinite(value)


def _sha(value):
    return (isinstance(value,str) and len(value)==64
            and all(c in "0123456789abcdef" for c in value))


def frame_observations(receipts, source, stream):
    """Project actual requested frames; absence is never an interval inference.

    The full acquisition receipt retains literal text, associations and model
    provenance. This projection deliberately carries no translated text or
    invented geometry. Contradictory evidence is explicitly unknown.
    """
    if type(stream) is not int or not _sha(source.get("content_sha256")):
        return []
    result=[]
    for receipt in receipts:
        if (receipt.get("kind")!="visual" or receipt.get("status")!="observed"
                or (receipt.get("provider") or {}).get("media_sha256")!=source["content_sha256"]
                or receipt.get("visual_stream")!={"selector":"0:V:0","container_index":stream}
                or not _sha(receipt.get("observation_sha256"))):
            continue
        absent=set(receipt.get("caption_absent_frame_ids",[]))
        for frame in receipt.get("frames",[]):
            fid=frame.get("id")
            seek=frame.get("requested_seek_s")
            if not _sha(frame.get("sha256")) or not _number(seek) or not 0<=seek<=source["duration_s"]:
                continue
            visible=[v for v in receipt.get("visible_text",[])
                     if fid in v.get("frame_ids",[]) and v.get("text_kind")=="dialogue_caption"]
            present=sorted({v["caption_id"] for v in visible if v.get("source_language_match") is True})
            # A dialogue caption of uncertain language also defeats a negative.
            conflict=bool(fid in absent and visible)
            status=("unknown" if conflict else "present" if present else
                    "absent" if fid in absent else "unknown")
            if status=="unknown" and not conflict:
                continue
            fact={"time_s":seek,"frame_sha256":frame["sha256"],
                  "evidence_sha256":receipt["observation_sha256"],
                  "video_stream_index":stream,"status":status,
                  "caption_ids":present,"contradictory":conflict,
                  "source_language":receipt["provider"].get("source_language") or "unknown"}
            if fact not in result:
                result.append(fact)
    return result


def admit_frame_observations(doc):
    """Validate optional shared observation facts, not their semantic truth."""
    facts=doc.get("caption_frame_observations",[])
    if not isinstance(facts,list):
        raise ValueError("Invalid caption frame observations")
    for item in facts:
        if (not isinstance(item,dict) or set(item)!={"time_s","frame_sha256","evidence_sha256",
                "video_stream_index","status","caption_ids","contradictory","source_language"}
                or not _number(item["time_s"]) or not 0<=item["time_s"]<=doc["duration_s"]
                or not _sha(item["frame_sha256"]) or not _sha(item["evidence_sha256"])
                or type(item["video_stream_index"]) is not int
                or item["video_stream_index"]!=doc.get("video_stream_index")
                or item["status"] not in ("present","absent","unknown")
                or type(item["contradictory"]) is not bool
                or not isinstance(item["source_language"],str) or not item["source_language"].strip()
                or not isinstance(item["caption_ids"],list)
                or any(not isinstance(v,str) or not v.startswith("visible-") for v in item["caption_ids"])
                or item["status"]=="present" and not item["caption_ids"]
                or item["status"]=="absent" and (item["caption_ids"] or item["contradictory"])
                or item["contradictory"] and item["status"]!="unknown"):
            raise ValueError("Invalid caption frame observation")
    return facts


def static_context(doc):
    """Bind static routing inputs, excluding observations generated by this run."""
    if doc is None:
        return None
    return {k:deepcopy(v) for k,v in doc.items() if k!="caption_frame_observations"}


def routing_context(doc, receipts, source, targets):
    """Bounded frame/interval routing facts; sparse empty samples imply unknown."""
    if doc is None:
        return None
    facts=frame_observations(receipts,source,doc.get("video_stream_index"))
    samples=doc.get("samples",[])
    regions=[]
    for sample in samples:
        for region in sample["caption_candidates"]:
            if region not in regions:
                regions.append(region)
    result={"video_status":doc.get("status","unknown"),
            "sample_count":len(samples),
            "candidate_sample_count":sum(bool(s["caption_candidates"]) for s in samples),
            "candidate_regions":regions[:8],
            "candidate_regions_are_unconfirmed":True,
            "prior_present_frames":sum(f["status"]=="present" for f in facts),
            "prior_absent_frames":sum(f["status"]=="absent" for f in facts),
            "occurrences":[]}
    for target in targets:
        start,end=target.get("start"),target.get("end")
        status="unknown"
        points=[]
        intervals=[]
        if _number(start) and _number(end) and start<end:
            points=[f for f in facts if start<=f["time_s"]<=end]
            intervals=[o for o in doc.get("caption_observations",[])
                       if o["interval_s"][0]<end and o["interval_s"][1]>start]
            positive=any(f["status"]=="present" for f in points) or any(o["status"]=="present" for o in intervals)
            negative=any(f["status"]=="absent" for f in points)
            interval_absent=any(o["status"]=="absent" and o["interval_s"][0]<=start
                                and o["interval_s"][1]>=end for o in intervals)
            conflict=(any(f["contradictory"] for f in points)
                      or positive and interval_absent
                      or any(p["status"]=="present" and n["status"]=="absent"
                             and p["time_s"]==n["time_s"] for p in points for n in points))
            if conflict:
                status="conflicting"
            elif positive and negative:
                status="intermittent_at_observed_frames"
            elif positive:
                status="present_in_observed_interval"
            elif interval_absent and all(o["status"]=="absent" for o in intervals):
                status="supported_interval_absence"
            elif negative:
                status="absent_at_observed_frames"
        result["occurrences"].append({"id":target["utterance_id"],"status":status,
             "frame_evidence":points[-8:],
             "interval_evidence":[{"status":o["status"],"interval_s":o["interval_s"],
                                   "evidence_sha256":o["evidence_sha256"]} for o in intervals[-8:]]})
    return result


def merge_frame_observations(doc, receipts, source):
    """Share frame facts with renderer/source assessment, without new acquisition."""
    if doc is None:
        return None
    result=deepcopy(doc)
    facts=list(result.get("caption_frame_observations",[]))
    for fact in frame_observations(receipts,source,result.get("video_stream_index")):
        if fact not in facts:
            facts.append(fact)
    if facts:
        result["caption_frame_observations"]=facts
    return result
